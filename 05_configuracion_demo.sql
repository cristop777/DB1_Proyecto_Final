-- Registra la estación antes de configurar la tabla.
DROP TRIGGER IF EXISTS trg_autoaudit_contexto
ON autoaudit.evento_auditoria;

CREATE TRIGGER trg_autoaudit_contexto
BEFORE INSERT ON autoaudit.evento_auditoria
FOR EACH ROW
EXECUTE FUNCTION autoaudit.fn_completar_contexto();

-- Audita la columna correo para las tres operaciones.
SELECT autoaudit.configurar_columna(
    'public',
    'clientes_demo',
    'correo',
    ARRAY['insert', 'update', 'delete']::text[]
);