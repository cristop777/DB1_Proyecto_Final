-- Configura la tabla de demostración del sistema de trazabilidad.
-- Ejecuta este archivo conectado a control_cambios_db,
-- después de 02_esquema_tablas.sql, 03_funciones.sql
-- y 04_permisos.sql.
--
-- IMPORTANTE:
-- Este archivo elimina y vuelve a crear public.clientes_demo.
-- Se perderán los datos que existan actualmente en esa tabla.

-- Elimina la tabla demo anterior, junto con los objetos que dependan de ella.
DROP TABLE IF EXISTS public.clientes_demo CASCADE;

-- Crea la tabla usada para demostrar las operaciones auditadas.
CREATE TABLE public.clientes_demo (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre text NOT NULL,
    correo text NOT NULL UNIQUE,
    ciudad text
);

-- Sincroniza las tablas y columnas visibles en el diccionario de PostgreSQL.
SELECT trazabilidad.trz_sincronizar_diccionario();

-- Instala el trigger que completa el contexto del evento,
-- como la dirección IP y el nombre de la estación de trabajo.
DROP TRIGGER IF EXISTS trg_trz_contexto
ON trazabilidad.trz_evento;

CREATE TRIGGER trg_trz_contexto
BEFORE INSERT ON trazabilidad.trz_evento
FOR EACH ROW
EXECUTE FUNCTION trazabilidad.trz_completar_contexto();

-- Habilita auditoría para nombre, correo y ciudad
-- en las operaciones INSERT, UPDATE y DELETE.
SELECT trazabilidad.trz_configurar_columna(
    'public',
    'clientes_demo',
    'nombre',
    ARRAY['insert', 'update', 'delete']::text[]
);

SELECT trazabilidad.trz_configurar_columna(
    'public',
    'clientes_demo',
    'correo',
    ARRAY['insert', 'update', 'delete']::text[]
);

SELECT trazabilidad.trz_configurar_columna(
    'public',
    'clientes_demo',
    'ciudad',
    ARRAY['insert', 'update', 'delete']::text[]
);

-- Permite a la aplicación web consultar y administrar clientes demo.
-- Estos permisos no incluyen las tablas de configuración ni la bitácora.
GRANT USAGE ON SCHEMA public TO autoaudit_app;

GRANT SELECT, INSERT, UPDATE, DELETE
ON TABLE public.clientes_demo
TO autoaudit_app;

-- Permite generar y consultar los identificadores de clientes.
GRANT USAGE, SELECT
ON SEQUENCE public.clientes_demo_id_seq
TO autoaudit_app;