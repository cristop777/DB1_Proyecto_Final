-- Crea la tabla de ejemplo si aún no existe.
-- Elimina la tabla de demostración si ya existe.
-- CASCADE también elimina objetos que dependan de ella.
DROP TABLE IF EXISTS public.clientes_demo CASCADE;

-- Crea nuevamente la tabla de demostración.
CREATE TABLE public.clientes_demo (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre text NOT NULL,
    correo text NOT NULL UNIQUE,
    ciudad text
);

-- Completa el diccionario del sistema con las tablas y columnas actuales.
